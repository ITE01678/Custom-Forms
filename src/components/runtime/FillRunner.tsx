import { useMemo, useState, type ReactNode } from "react";
import { RuntimeShell } from "./RuntimeShell";
import { FieldRenderer } from "./fields/FieldRenderer";
import { AutofillField } from "./fields/AutofillField";
import { DynamicChoiceField } from "./fields/DynamicChoiceField";
import { ConnectorTableField } from "./fields/ConnectorTableField";
import { FileUploadField } from "./fields/FileUploadField";
import { GraphImage } from "../common/GraphImage";
import { RichText } from "../common/RichText";
import { getVisibleFields, resolveFirstSectionId, resolveNextSectionId, shuffleSectionOrder } from "../../formsSchema/branching";
import { validateFields, type FieldError } from "../../formsSchema/validation";
import type { SectionAccess } from "../../formsSchema/routingAccess";
import { useAuth } from "../../auth/useAuth";
import { textStyleToCss } from "../../lib/textStyle";
import { formatAnswer } from "../../lib/formatAnswer";
import type { AnswerValue, FormDefinition, FormField } from "../../formsSchema/types";

interface Props {
  form: FormDefinition;
  /** Stable id used for this response's file-attachment paths (and, once
   *  submitted, the response's own id) — generated by the caller so it's
   *  consistent from the first file upload through to the final submit. */
  responseId: string;
  initialAnswers?: Record<string, AnswerValue>;
  /** Omit (or pass []) for a fresh fill-out — FillRunner resolves the first
   *  visible section itself (respecting shuffleSections). Pass the actual
   *  path for resuming a draft/edit, so Back replays it exactly. */
  initialSectionIds?: string[];
  /** Approval-routing's per-stage section restriction (formsSchema/
   *  routingAccess.ts) — omitted entirely for a form with no routing, or
   *  the ordinary create/self-edit paths, which always see/edit everything.
   *  Sections outside `visibleSectionIds` are transparently skipped during
   *  navigation (reusing the same mechanism conditional section visibility
   *  already uses); sections in `visibleSectionIds` but not
   *  `editableSectionIds` are shown read-only for context. */
  sectionAccess?: SectionAccess;
  /** Shown as a banner above the form — e.g. "You already submitted this on
   *  <date>. Editing your response — changes are logged." for the edit-mode gate. */
  banner?: ReactNode;
  /** Edit policy's requireReasonForEdit — collects a short reason on the
   *  final step and passes it through to onSubmit. */
  requireReason?: boolean;
  /** "Save and finish later" — omitted entirely (no button shown) when not
   *  provided, e.g. in edit mode or builder Preview. */
  onSaveDraft?: (answers: Record<string, AnswerValue>, visitedSectionIds: string[]) => Promise<void>;
  /** Called after the last step validates successfully. Throw to surface an
   *  error inline instead of advancing (the runtime doesn't navigate away on
   *  its own — the caller decides what happens after a successful submit,
   *  which is what lets the builder's Preview mode reuse this unchanged). */
  onSubmit: (answers: Record<string, AnswerValue>, reason?: string) => Promise<void>;
  /** An extra button next to Submit on the last step — used by the approver
   *  review flow for "Reject" (approving reuses the normal onSubmit path).
   *  Deliberately skips field validation (an approver should be able to
   *  reject even if a field looks invalid/incomplete), unlike onSubmit. */
  secondaryAction?: {
    label: string;
    onClick: (answers: Record<string, AnswerValue>) => Promise<void>;
  };
}

/**
 * The shared page-by-page fill-out engine — used by the live `/f/:slug`
 * route (fresh submissions, edits, and resumed drafts) and the builder's
 * Preview mode, so preview and reality can't drift (per the plan's Builder
 * UX note).
 */
export function FillRunner({
  form,
  responseId,
  initialAnswers,
  initialSectionIds,
  sectionAccess,
  banner,
  requireReason,
  onSaveDraft,
  onSubmit,
  secondaryAction,
}: Props) {
  const { email } = useAuth();

  // Shuffle only affects the natural "next section in order" fallback —
  // branchRules/defaultNext (specific target ids) always take priority, so
  // this can't break configured branching. Computed once per mount.
  const effectiveSections = useMemo(
    () => (form.settings.shuffleSections ? shuffleSectionOrder(form.sections) : form.sections),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [form.id]
  );

  const sectionExtraCheck = useMemo(
    () => (sectionAccess ? (s: { id: string }) => sectionAccess.visibleSectionIds.has(s.id) : undefined),
    [sectionAccess]
  );

  const [answers, setAnswers] = useState<Record<string, AnswerValue>>(initialAnswers ?? {});
  const [visitedSectionIds, setVisitedSectionIds] = useState<string[]>(() => {
    if (initialSectionIds && initialSectionIds.length > 0) return initialSectionIds;
    const first = resolveFirstSectionId(effectiveSections, initialAnswers ?? {}, sectionExtraCheck);
    return first ? [first] : [];
  });
  const [errors, setErrors] = useState<FieldError[]>([]);
  const [reason, setReason] = useState("");
  const [reasonError, setReasonError] = useState<string | null>(null);
  const [submitting, setSubmitting] = useState(false);
  const [submitError, setSubmitError] = useState<string | null>(null);
  const [savingDraft, setSavingDraft] = useState(false);
  const [draftSaved, setDraftSaved] = useState(false);

  const currentSectionId = visitedSectionIds[visitedSectionIds.length - 1] ?? null;
  const currentSection = useMemo(
    () => effectiveSections.find((s) => s.id === currentSectionId) ?? null,
    [effectiveSections, currentSectionId]
  );
  const visibleFields = useMemo(
    () => (currentSection ? getVisibleFields(currentSection, answers) : []),
    [currentSection, answers]
  );
  const isCurrentSectionEditable = !sectionAccess || sectionAccess.editableSectionIds.has(currentSection?.id ?? "");

  if (!currentSection) {
    return (
      <RuntimeShell title={form.title} titleStyle={form.titleStyle} description={form.description} branding={form.branding}>
        <p>This form has no sections yet.</p>
      </RuntimeShell>
    );
  }

  function setAnswer(fieldId: string, value: AnswerValue) {
    setAnswers((prev) => ({ ...prev, [fieldId]: value }));
    setErrors((prev) => prev.filter((e) => e.fieldId !== fieldId));
    setDraftSaved(false);
  }

  function handleBack() {
    setVisitedSectionIds((prev) => prev.slice(0, -1));
    setErrors([]);
  }

  const isLastStep = resolveNextSectionId(currentSection.id, effectiveSections, answers, sectionExtraCheck) === null;

  async function handleSaveDraft() {
    if (!onSaveDraft) return;
    setSavingDraft(true);
    try {
      await onSaveDraft(answers, visitedSectionIds);
      setDraftSaved(true);
    } catch (err) {
      setSubmitError(err instanceof Error ? err.message : String(err));
    } finally {
      setSavingDraft(false);
    }
  }

  async function handleNext() {
    // A read-only (context-only) section has nothing this actor entered —
    // nothing to validate before moving on.
    const fieldErrors = isCurrentSectionEditable ? validateFields(visibleFields, answers) : [];
    if (fieldErrors.length > 0) {
      setErrors(fieldErrors);
      return;
    }

    const nextId = resolveNextSectionId(currentSection!.id, effectiveSections, answers, sectionExtraCheck);
    if (nextId) {
      setVisitedSectionIds((prev) => [...prev, nextId]);
      return;
    }

    if (requireReason && reason.trim() === "") {
      setReasonError("Please give a short reason for this change.");
      return;
    }

    setSubmitting(true);
    setSubmitError(null);
    setReasonError(null);
    try {
      await onSubmit(answers, requireReason ? reason.trim() : undefined);
    } catch (err) {
      setSubmitError(err instanceof Error ? err.message : String(err));
    } finally {
      setSubmitting(false);
    }
  }

  async function handleSecondaryAction() {
    if (!secondaryAction) return;
    setSubmitting(true);
    setSubmitError(null);
    try {
      await secondaryAction.onClick(answers);
    } catch (err) {
      setSubmitError(err instanceof Error ? err.message : String(err));
    } finally {
      setSubmitting(false);
    }
  }

  const totalSections = Math.max(form.sections.length, 1);
  const progress = Math.min(1, visitedSectionIds.length / totalSections);

  return (
    <RuntimeShell title={form.title} titleStyle={form.titleStyle} description={form.description} branding={form.branding}>
      {banner && <div className="runtime__banner">{banner}</div>}

      {form.sections.length > 1 && form.settings.showProgressBar && (
        <div className="runtime__progress-track">
          <div className="runtime__progress-fill" style={{ width: `${progress * 100}%` }} />
        </div>
      )}

      {currentSection.imageUrl && (
        <GraphImage className="fill-runner__section-image" src={currentSection.imageUrl} alt="" />
      )}
      <h2 className="fill-runner__section-title" style={textStyleToCss(currentSection.titleStyle)}>
        {currentSection.title}
      </h2>
      {currentSection.description && (
        <RichText className="fill-runner__section-desc" html={currentSection.description} />
      )}
      {!isCurrentSectionEditable && (
        <p className="fill-runner__readonly-note">
          🔒 Shown for context — this section was completed at an earlier stage.
        </p>
      )}

      {isCurrentSectionEditable
        ? visibleFields.map((field) => renderField(field, answers, setAnswer, errors, email ?? "", form.id, responseId))
        : visibleFields.map((field) => (
            <div className="fill-field" key={field.id}>
              <span className="fill-field__label" style={textStyleToCss(field.labelStyle)}>
                {field.label}
              </span>
              <p className="fill-field__readonly-value">{formatAnswer(answers[field.id] ?? null, field)}</p>
            </div>
          ))}

      {isLastStep && requireReason && (
        <div className="fill-field">
          <label className="fill-field__label" htmlFor="edit-reason">
            Reason for this change<span className="fill-field__required-mark">*</span>
          </label>
          <input
            id="edit-reason"
            className="fill-field__input"
            type="text"
            value={reason}
            onChange={(e) => setReason(e.target.value)}
          />
          {reasonError && <div className="error-text">{reasonError}</div>}
        </div>
      )}

      {submitError && <p className="error-text">{submitError}</p>}

      <div className="fill-runner__nav">
        {visitedSectionIds.length > 1 ? (
          <button onClick={handleBack} disabled={submitting}>
            Back
          </button>
        ) : (
          <span />
        )}
        <span className="fill-runner__nav-spacer" />
        {onSaveDraft && (
          <button onClick={handleSaveDraft} disabled={savingDraft || submitting}>
            {savingDraft ? "Saving…" : draftSaved ? "Saved ✓" : "Save and finish later"}
          </button>
        )}
        {isLastStep && secondaryAction && (
          <button onClick={handleSecondaryAction} disabled={submitting}>
            {secondaryAction.label}
          </button>
        )}
        <button className="btn-primary" onClick={handleNext} disabled={submitting}>
          {submitting ? "Submitting…" : isLastStep ? form.branding.submitButtonText || "Submit" : "Next"}
        </button>
      </div>
    </RuntimeShell>
  );
}

/** Dispatches each visible field to the renderer matching its fillMode/type. */
function renderField(
  field: FormField,
  answers: Record<string, AnswerValue>,
  setAnswer: (fieldId: string, value: AnswerValue) => void,
  errors: FieldError[],
  respondentEmail: string,
  formId: string,
  responseId: string
) {
  const error = errors.find((e) => e.fieldId === field.id)?.message;
  const onChange = (v: AnswerValue) => setAnswer(field.id, v);

  if (field.type === "repeatingTable") {
    return (
      <ConnectorTableField
        key={field.id}
        field={field}
        respondentEmail={respondentEmail}
        priorAnswers={answers}
        value={answers[field.id] ?? null}
        onChange={onChange}
        error={error}
      />
    );
  }

  // A choice field whose OPTIONS (not a single auto-filled value) come from
  // a connector lookup — checked before the generic connector-autofill
  // branch below, which assumes a scalar resolved value.
  if (
    field.fillMode === "connector-autofill" &&
    field.connectorAutofill?.dynamicOptions &&
    (field.type === "singleChoice" || field.type === "multiChoice")
  ) {
    return (
      <DynamicChoiceField
        key={field.id}
        field={field}
        respondentEmail={respondentEmail}
        priorAnswers={answers}
        value={answers[field.id] ?? (field.type === "multiChoice" ? [] : null)}
        onChange={onChange}
        error={error}
      />
    );
  }

  // Checked BEFORE the fileUpload branch below: a fileUpload field can also
  // be configured with fillMode "graph-autofill"/"connector-autofill" (e.g.
  // auto-attach a reference document resolved by lookup key) — dispatching
  // on field.type first would silently ignore that config and always show
  // the plain manual uploader.
  if (field.fillMode !== "manual") {
    return (
      <AutofillField
        key={field.id}
        field={field}
        respondentEmail={respondentEmail}
        priorAnswers={answers}
        value={answers[field.id] ?? null}
        formId={formId}
        responseId={responseId}
        onChange={onChange}
        error={error}
      />
    );
  }

  if (field.type === "fileUpload") {
    return (
      <FileUploadField
        key={field.id}
        field={field}
        formId={formId}
        responseId={responseId}
        value={answers[field.id] ?? null}
        onChange={onChange}
        error={error}
      />
    );
  }

  return <FieldRenderer key={field.id} field={field} value={answers[field.id] ?? null} onChange={onChange} error={error} />;
}
